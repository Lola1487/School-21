#!/bin/bash

# Проверка аргументов
if [ $# -ne 1 ]; then
    echo "Ошибка: скрипт требует один параметр - путь до директории"
    echo "Пример: $0 /path/to/directory/"
    exit 1
fi

DIR="$1"

# Проверка завершающего слеша
if [[ "${DIR: -1}" != "/" ]]; then
    echo "Ошибка: путь должен заканчиваться символом '/'"
    exit 1
fi

# Проверка существования директории
if [ ! -d "$DIR" ]; then
    echo "Ошибка: директория '$DIR' не существует"
    exit 1
fi

# Проверка доступности директории
if [ ! -r "$DIR" ]; then
    echo "Ошибка: нет прав на чтение директории '$DIR'"
    exit 1
fi
